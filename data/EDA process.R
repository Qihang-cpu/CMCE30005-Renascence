    comma(yr[year == 2025, N]), yr[year == 2025, N] / yr[year == 2019, N])

season <- rv_clean[year %in% 2023:2025, .N, by = .(year, m = as.integer(format(date, "%m")))]
season[, share := N / sum(N), by = year]
season <- season[, .(share = mean(share)), by = m][order(m)]
season[, peak := share >= sort(share, decreasing = TRUE)[4]]
p <- ggplot(season, aes(factor(month.abb[m], levels = month.abb), share, fill = peak)) +
  geom_col(width = 0.7, show.legend = FALSE) +
  geom_hline(yintercept = 1 / 12, linetype = "dashed", colour = "grey40") +
  scale_fill_manual(values = c(`FALSE` = grey, `TRUE` = blue)) +
  scale_y_continuous(labels = percent) +
  labs(title = "Seasonality: share of each year's stays by month (2023-2025)",
       subtitle = "Blue = 4 busiest months. Dashed line = an even 1/12 per month",
       x = NULL, y = "Share of year's reviews")
save_fig(p, "08_seasonality.png", w = 7, h = 4.5)
add("Busiest months (2023-25): %s", paste(month.abb[season[peak == TRUE, m]], collapse = ", "))

