# 5. CORRELATIONS between key numeric variables
# =============================================================================

num_vars <- c("log_price", "accommodates", "bedrooms", "bathrooms", "n_amenities",
              "dist_cbd_km", "minimum_nights", "review_scores_rating",
              "rv_last_12m", "avail_rate_365", "host_listings")
cm <- cor(bk[, ..num_vars], use = "pairwise.complete.obs")
cm_long <- as.data.table(as.table(cm))
setnames(cm_long, c("var1", "var2", "r"))
cm_long[, `:=`(var1 = factor(var1, levels = num_vars), var2 = factor(var2, levels = rev(num_vars)))]
p <- ggplot(cm_long, aes(var1, var2, fill = r)) +
  geom_tile(colour = "white", linewidth = 0.6) +
  geom_text(aes(label = sprintf("%.2f", r)), size = 2.6, colour = "grey15") +
  scale_fill_gradient2(low = orange, mid = "#f0efec", high = blue, midpoint = 0,
                       limits = c(-1, 1), name = "r") +
  labs(title = "Correlation between key listing variables",
       subtitle = "Bookable listings. Blue = move together, orange = move in opposite directions",
       x = NULL, y = NULL) +
  theme(axis.text.x = element_text(angle = 40, hjust = 1), panel.grid = element_blank())
save_fig(p, "13_correlation_heatmap.png", w = 7.5, h = 6.5)
add("Correlation log_price vs accommodates: %.2f | vs dist_cbd_km: %.2f",
    cm["log_price", "accommodates"], cm["log_price", "dist_cbd_km"])

