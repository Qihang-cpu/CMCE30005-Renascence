monthly <- rv_clean[date >= as.IDate("2015-01-01") & date < as.IDate("2026-06-01"),
                    .N, by = .(month = as.IDate(format(date, "%Y-%m-01")))][order(month)]
p <- ggplot(monthly, aes(month, N)) +
  geom_line(colour = blue, linewidth = 0.6) +
  scale_y_continuous(labels = comma) +
  labs(title = "Reviews per month - a proxy for completed stays",
       subtitle = "COVID collapse in 2020-21, then demand roughly tripled vs 2019",
