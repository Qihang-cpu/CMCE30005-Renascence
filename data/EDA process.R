library(data.table)
library(ggplot2)
library(scales)

if (!file.exists("data/processed/listings_master.rds")) source("data/Data cleaning .R")

lm_all   <- readRDS("data/processed/listings_master.rds")
cal_day  <- readRDS("data/processed/calendar_daily.rds")
rv_clean <- readRDS("data/processed/reviews_clean.rds")

fig_dir <- "outputs/figures"
dir.create(fig_dir, showWarnings = FALSE, recursive = TRUE)

# --- One colour system for every chart ---------------------------------------
blue   <- "#2a78d6"   # main colour, single-series charts
orange <- "#eb6834"   # second category / contrast
aqua   <- "#1baf7a"   # third category
yellow <- "#eda100"   # fourth category
grey   <- "#d8d8d4"   # background / neutral
room_cols <- c("Entire home/apt" = blue, "Private room" = orange,
               "Shared room" = aqua, "Hotel room" = yellow)

theme_set(theme_minimal(base_size = 11) +
            theme(panel.grid.minor = element_blank(),
                  plot.title = element_text(face = "bold"),
                  plot.title.position = "plot"))

save_fig <- function(plot, name, w = 8, h = 5) {
  ggsave(file.path(fig_dir, name), plot, width = w, height = h, dpi = 150, bg = "white")
  invisible(plot)
}

bk <- lm_all[bookable == TRUE]          # bookable listings with a price
summary_lines <- c("EDA summary - generated by data/EDA process.R", "")
add <- function(...) summary_lines <<- c(summary_lines, sprintf(...))

add("Listings (clean): %s | bookable with price: %s",
    comma(nrow(lm_all)), comma(nrow(bk)))

# =============================================================================
# 1. SUPPLY - where are the listings and what are they?
# =============================================================================

lga_n <- lm_all[, .N, by = lga][order(N)]
lga_n[, lga := factor(lga, levels = lga)]
p <- ggplot(lga_n, aes(N, lga)) +
  geom_col(fill = blue, width = 0.7) +
  geom_text(aes(label = comma(N)), hjust = -0.15, size = 3, colour = "grey30") +
  scale_x_continuous(labels = comma, expand = expansion(mult = c(0, .12))) +
  labs(title = "Airbnb supply by Local Government Area",
       subtitle = sprintf("City of Melbourne alone holds %.0f%% of all listings",
                          100 * lga_n[lga == "Melbourne", N] / nrow(lm_all)),
       x = "Listings", y = NULL)
save_fig(p, "01_supply_by_lga.png", h = 7)
add("Top LGA: Melbourne %s listings (%.1f%%)", comma(lga_n[lga == "Melbourne", N]),
    100 * lga_n[lga == "Melbourne", N] / nrow(lm_all))

room_n <- lm_all[, .N, by = room_type][, share := N / sum(N)]
p <- ggplot(room_n, aes(room_type, N, fill = room_type)) +
  geom_col(width = 0.6, show.legend = FALSE) +
  geom_text(aes(label = sprintf("%s (%.0f%%)", comma(N), 100 * share)),
            vjust = -0.4, size = 3.2, colour = "grey30") +
  scale_fill_manual(values = room_cols) +
  scale_y_continuous(labels = comma, expand = expansion(mult = c(0, .1))) +
  labs(title = "Listings by room type", x = NULL, y = "Listings")
save_fig(p, "02_room_type_mix.png", w = 7, h = 4.5)
for (i in seq_len(nrow(room_n))) add("Room type %s: %s (%.1f%%)", room_n$room_type[i],
                                     comma(room_n$N[i]), 100 * room_n$share[i])

